import mongoose from "mongoose";
import { CHANGE_CATEGORIES } from "../services/europassService.js";

// One entry of the "What we improved" report
const changeSchema = new mongoose.Schema(
    {
        section: { type: String, default: "" },
        category: { type: String, enum: CHANGE_CATEGORIES, required: true },
        before: { type: String, default: "" },
        after: { type: String, required: true },
        reason: { type: String, default: "" },
    },
    { _id: false }
);

const improvedResumeSchema = new mongoose.Schema(
    {
        // FK → analyses._id  (one Analysis has at most ONE ImprovedResume — regenerating replaces it)
        analysisId: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "Analysis",
            required: true,
            unique: true,
        },
        // FK → resumes._id and users._id (kept for ownership checks and cascade delete)
        resumeId: { type: mongoose.Schema.Types.ObjectId, ref: "Resume", required: true, index: true },
        userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, index: true },
        // The CV in Europass structure as generated by the AI (kept unchanged so the user can reset).
        // Its exact shape is guaranteed by normalizeEuropassCv() in services/europassService.js.
        europassCv: { type: mongoose.Schema.Types.Mixed, required: true },
        // The user's own edited version (same shape). null = use the AI version.
        editedCv: { type: mongoose.Schema.Types.Mixed, default: null },
        editedAt: { type: Date, default: null },
        changes: { type: [changeSchema], default: [] },
    },
    {
        timestamps: { createdAt: true, updatedAt: false },
        minimize: false, // keep empty objects/strings inside europassCv
        toJSON: {
            virtuals: true,
            transform(_doc, ret) {
                ret.id = ret._id.toString();
                delete ret._id;
                delete ret.__v;
                return ret;
            },
        },
    }
);

// The cover letter generated from this improved resume (0 or 1). Only included when populated.
improvedResumeSchema.virtual("coverLetter", {
    ref: "CoverLetter",
    localField: "_id",
    foreignField: "improvedResumeId",
    justOne: true,
});

// The CV to show / print / use for the cover letter: the user's edits win over the AI version
improvedResumeSchema.methods.currentCv = function () {
    return this.editedCv ?? this.europassCv;
};

export default mongoose.model("ImprovedResume", improvedResumeSchema);
