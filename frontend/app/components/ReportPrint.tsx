// Printable analysis report ("Download Report" → browser print → Save as PDF).
// Only visible when printing; the normal result page is hidden then (it is marked no-print).
const CATEGORIES = [
    { key: "toneAndStyle", label: "Tone & Style" },
    { key: "content", label: "Content" },
    { key: "structure", label: "Structure" },
    { key: "skills", label: "Skills" },
] as const;

const rating = (score: number) => (score > 70 ? "Strong" : score > 49 ? "Good start" : "Needs work");

function TipList({ tips }: { tips: { type: "good" | "improve"; tip: string; explanation?: string }[] }) {
    if (!tips.length) return <p className="report-muted">No tips for this category.</p>;
    return (
        <ul className="report-tips">
            {tips.map((t, i) => (
                <li key={i} className={t.type === "good" ? "report-good" : "report-improve"}>
                    <b>{t.type === "good" ? "✓ Strength" : "! Improve"}: {t.tip}</b>
                    {t.explanation && <span> — {t.explanation}</span>}
                </li>
            ))}
        </ul>
    );
}

export default function ReportPrint({ resume, analysis }: { resume: Resume; analysis: Analysis }) {
    const f = analysis.feedback;
    const after = analysis.improved?.afterFeedback;
    return (
        <article className="report-print hidden print:block">
            <header className="report-header">
                <div>
                    <p className="report-brand">RESUMIND</p>
                    <h1 className="report-title">Resume Analysis Report</h1>
                    <p className="report-muted">
                        {[analysis.jobTitle, analysis.companyName].filter(Boolean).join(" at ")} · {resume.originalName}
                    </p>
                </div>
                <div className="report-score">
                    <span>{f.overallScore}</span>
                    <small>/100 overall</small>
                </div>
            </header>
            <p className="report-muted">Analyzed on {new Date(analysis.createdAt).toLocaleString()}</p>

            <h2 className="report-h2">Score overview</h2>
            <table className="report-table">
                <thead><tr><th>Category</th><th>Score</th><th>Rating</th>{after && <th>After Europass CV</th>}</tr></thead>
                <tbody>
                    <tr><td>ATS (Applicant Tracking System)</td><td>{f.ATS.score}/100</td><td>{rating(f.ATS.score)}</td>{after && <td>{after.ATS.score}/100</td>}</tr>
                    {CATEGORIES.map(({ key, label }) => (
                        <tr key={key}><td>{label}</td><td>{f[key].score}/100</td><td>{rating(f[key].score)}</td>{after && <td>{after[key].score}/100</td>}</tr>
                    ))}
                    <tr className="report-total"><td>Overall</td><td>{f.overallScore}/100</td><td>{rating(f.overallScore)}</td>{after && <td>{after.overallScore}/100</td>}</tr>
                </tbody>
            </table>

            <section className="report-section">
                <h2 className="report-h2">ATS — {f.ATS.score}/100</h2>
                <TipList tips={f.ATS.tips} />
            </section>
            {CATEGORIES.map(({ key, label }) => (
                <section key={key} className="report-section">
                    <h2 className="report-h2">{label} — {f[key].score}/100</h2>
                    <TipList tips={f[key].tips} />
                </section>
            ))}

            <footer className="report-footer">
                Generated by Resumind · AI Resume Analyzer (CSE4204-8A-T05). AI feedback is a guide — check every suggestion before you apply.
            </footer>
        </article>
    );
}
